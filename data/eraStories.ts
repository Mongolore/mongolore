/**
 * Story-first content for each era on the full map (/map), written for young
 * readers: a hook, three fast facts, clickable map hotspots, a then-vs-now
 * bridge and a one-question quiz. Keyed by `Era.id`; `npm run check:data`
 * checks every era has one.
 *
 * Writing notes:
 * - Short sentences, active verbs, one modern analogy where a term needs it.
 * - `hook.summary`: two sentences on why this moment mattered.
 * - `hotspots`: 4–6 cards, each `text` at most 80 words. Every era needs one
 *   of each kind. Pin a card to a place from `ERA_MAPS[era].places` by its
 *   `name`, or give `at` ([lon, lat] inside the era's view) for a point on a
 *   route or with no place symbol.
 * - `quiz.answer` is the index of the correct option.
 */
export type HotspotKind = "capital" | "turning" | "route" | "secret";

export type Hotspot = {
  kind: HotspotKind;
  title: string;
  text: string;
  /** `name` of a place in the era's `ERA_MAPS` entry. */
  place?: string;
  /** Where to pin the card when it isn't tied to a place. */
  at?: LonLat;
};

export type EraStory = {
  hook: { title: string; summary: string };
  facts: { leaders: string; size: string; goal: string };
  hotspots: Hotspot[];
  thenNow: string[];
  quiz: { question: string; options: string[]; answer: number; correct: string };
};

